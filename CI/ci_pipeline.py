# Annotations - geo-lod's own reading, in its own graph
# ---------------------------------------------------------------------------

def add_annotation_source(g: Graph) -> None:
    source = GEOLOD["GeoLodCIAnnotations_DataSource"]
    g.add((source, RDF.type, GEOLOD["DataSource"]))
    g.add((source, RDF.type, OWL.NamedIndividual))
    g.add((source, RDFS.label,
           Literal("geo-lod CI findspot annotations", lang="en")))
    g.add((source, RDFS.comment,
           Literal("Archaeological readings added to Campanian Ignimbrite "
                   "findspots by the geo-lod project, beyond what the findspot "
                   "table states in its spatialtype column. Not part of "
                   "campanian-ignimbrite-geo and not reproducible from it.",
                   lang="en")))
    g.add((source, DCTERMS.creator, ORCID_FLO))
    g.add((source, DCTERMS.source, URIRef(
        "https://github.com/Research-Squirrel-Engineers/"
        "GeoScience-FAIRification-LOD")))
    g.add((source, DCTERMS.license, CI_LICENSE))


def add_annotations(g: Graph, annotations: dict[str, dict]) -> int:
    """The curated reading, with the same shape as the SISAL annotations.

    Screened and found nothing is a result, and a different one from never
    looked at - which is why the boolean is written even where the
    archaeological flag is false. For CI only the annotated findspots carry it
    so far; screening the remaining rows is S3f.
    """
    add_annotation_source(g)
    source = GEOLOD["GeoLodCIAnnotations_DataSource"]
    collection = GEOLOD["CI_Archaeological_Collection"]
    g.add((collection, RDF.type, GEO["FeatureCollection"]))
    g.add((collection, RDFS.label,
           Literal("CI findspots with an archaeological record", lang="en")))

    n_arch = 0
    for ci_id, note in sorted(annotations.items(), key=lambda kv: int(kv[0])):
        site = CI[f"cisite_{ci_id}"]

        def value(column: str) -> str:
            return (note.get(column) or "").strip()

        if value("screened").lower() == "true":
            g.add((site, GEOLOD["screenedForArchaeology"],
                   Literal(True, datatype=XSD.boolean)))
        g.add((site, PROV.wasDerivedFrom, source))

        if value("isArchaeologicalSite").lower() != "true":
            continue
        n_arch += 1
        g.add((site, RDF.type, GEOLOD["CIArchaeologicalSite"]))
        g.add((site, RDF.type, CRMARCHAEO["A2_Stratigraphic_Volume_Unit"]))
        g.add((collection, RDFS.member, site))
        if value("arch_category"):
            g.add((site, GEOLOD["archaeologicalCategory"],
                   Literal(value("arch_category"), lang="en")))
        if value("arch_broader_context"):
            g.add((site, GEOLOD["archaeologicalBroaderContext"],
                   GEOLOD[value("arch_broader_context")]))
        if value("arch_note"):
            g.add((site, SKOS.note, Literal(value("arch_note"), lang="en")))
        if value("arch_confidence"):
            g.add((site, GEOLOD["archaeologicalConfidence"],
                   Literal(value("arch_confidence"), lang="en")))
        if value("wikidata_qid"):
            g.add((site, SKOS.closeMatch,
                   URIRef("http://www.wikidata.org/entity/"
                          + value("wikidata_qid"))))
    return n_arch


# ---------------------------------------------------------------------------
# Writing
# ---------------------------------------------------------------------------

def header(title: str, inputs: list[Path]) -> str:
    """File header without a clock: release plus the fingerprint of the run."""
    return (
        f"# {title}\n"
        "# Generated by CI/ci_pipeline.py\n"
        f"# release: {GEO_LOD_RELEASE}\n"
        "# fingerprint (input data + generator): "
        f"{content_fingerprint([str(p) for p in inputs])}\n"
        f"# Source: {CI_SOURCE_REPO}\n\n"
    )


def write(g: Graph, path: Path, title: str, inputs: list[Path]) -> None:
    body = g.serialize(format="turtle")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(header(title, inputs))
        fh.write(body)
    print(f"  ✓ {path.relative_to(ROOT)}  ({len(g):,} triples)")


class Tee:
    """Writes simultaneously to stdout and the report file."""

    def __init__(self, filepath: Path):
        self.file = open(filepath, "w", encoding="utf-8", newline="\n")
        self.stdout = sys.stdout
        try:
            self.stdout.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
        sys.stdout = self

    def write(self, data):
        self.stdout.write(data)
        self.file.write(data)

    def flush(self):
        self.stdout.flush()
        self.file.flush()

    def close(self):
        sys.stdout = self.stdout
        self.file.close()



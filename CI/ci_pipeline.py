# Main
# ---------------------------------------------------------------------------

def build() -> bool:
    step = iter(STEPS)

    print("\n" + "=" * 72)
    print("  Campanian Ignimbrite findspots to RDF")
    print("=" * 72)
    print(f"  Input:  {RAW_CSV.relative_to(ROOT)}")
    print(f"          {CURATED_CSV.relative_to(ROOT)}")

    print(f"\n  ▶ {next(step)}")
    rows = read_csv(RAW_CSV,
                    "It moved to data/raw/ci/ in S3e; the copies in CI/ and "
                    "archaeo-connect/ are gone.")
    missing = [c for c in CSV_COLUMNS if c not in (rows[0] if rows else {})]
    if missing:
        raise ValueError(f"columns missing from {RAW_CSV.name}: "
                         f"{', '.join(missing)}")
    ids = [text(row, "id") for row in rows]
    if len(set(ids)) != len(ids):
        raise ValueError("duplicate id in the findspot table")
    without_geometry = [i for i, row in zip(ids, rows) if not text(row, "wkt")]
    print(f"    {len(rows)} findspots, {len(rows) - len(without_geometry)} "
          f"with a geometry")
    if without_geometry:
        print(f"    ⚠  no geometry: {', '.join(without_geometry)} - the SHACL "
              f"shape requires one")

    print(f"\n  ▶ {next(step)}")
    annotations = {text(row, "ci_id"): row for row in read_csv(
        CURATED_CSV, "It is maintained by hand in geo-lod and is not an "
                     "export of campanian-ignimbrite-geo.")}
    unknown = sorted(set(annotations) - set(ids), key=lambda v: int(v or 0))
    if unknown:
        raise ValueError(f"annotated ids not in the findspot table: "
                         f"{', '.join(unknown)}")
    arch = archaeological_ids(rows, annotations)
    from_source = {text(row, "id") for row in rows
                   if "ArchaeologicalSite" in text(row, "spatialtype")}
    print(f"    {len(annotations)} annotated findspots")
    print(f"    {len(arch)} archaeological: {len(from_source)} from "
          f"spatialtype, {len(arch - from_source)} added by curation")

    print(f"\n  ▶ {next(step)}")
    g = build_graph()
    uris = add_findspots(g, rows, arch)
    add_feature_collection(
        g=g,
        collection_uri=CI["CIFindspotCollection"],
        label="Campanian Ignimbrite Findspot Collection",
        members=uris,
    )

    print(f"\n  ▶ {next(step)}")
    ann = build_graph()
    n_arch = add_annotations(ann, annotations)
    print(f"    {n_arch} archaeological findspots from the annotation table")

    print(f"\n  ▶ {next(step)}")
    add_generation_provenance(
        g,
        CI["ci_findspots_dataset"],
        CI["ci_findspots_generation"],
        inputs=[str(RAW_CSV), __file__],
        agents=[ORCID_FLO, CI_SOURCE_REPO],
        label="CI findspot RDF generation",
    )
    # Every findspot's script run hangs off the generation of this dump.
    # prov:wasInformedBy rather than prov:hadMember: the dataset is not a
    # prov:Collection, and membership is already in the FeatureCollection.
    for ci_id in ids:
        g.add((CI[f"cisite_{ci_id}_pyscript"], PROV.wasInformedBy,
               CI["ci_findspots_generation"]))
    add_generation_provenance(
        ann,
        CI["ci_site_annotations_dataset"],
        CI["ci_site_annotations_generation"],
        inputs=[str(CURATED_CSV), __file__],
        agents=[ORCID_FLO],
        label="geo-lod CI findspot annotations",
    )

    print(f"\n  ▶ {next(step)}")
    RDF_DIR.mkdir(parents=True, exist_ok=True)
    write(g, RDF_DIR / "ci_findspots.ttl",
          "ci_findspots.ttl — Campanian Ignimbrite findspot instance data",
          [RAW_CSV, Path(__file__)])
    write(ann, RDF_DIR / "ci_site_annotations.ttl",
          "ci_site_annotations.ttl — geo-lod's archaeological reading of the "
          "CI findspots",
          [CURATED_CSV, Path(__file__)])

    return True


def main() -> int:
    REPORT_DIR.mkdir(parents=True, exist_ok=True)
    tee = Tee(REPORT_DIR / "report.txt")
    try:
        ok = build()
    except Exception:
        import traceback
        traceback.print_exc()
        ok = False
    finally:
        tee.close()
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
